-- Atendimento de WhatsApp (Conversa Bridge Ai): ações que a EQUIPE comanda pelo
-- WhatsApp. Decisão do dono (21/11/2026):
-- - a IA pode marcar agenda, calcular/atualizar propostas e dar desconto;
-- - nada vai ao cliente sem a equipe aprovar: só "proposta_enviar" cria o link,
--   e só aceita o comando vindo de um número da equipe cadastrado aqui.
--
-- Segurança:
-- - toda ação de escrita exige a chave da empresa + a permissão (scope) da ação
--   + o telefone de quem deu o comando estar em crm_read_keys.operator_phones;
-- - o cliente só é achado dentro da empresa da chave;
-- - limite de 60 ações de escrita por hora por chave; tudo fica em crm_team_actions;
-- - desconto até crm_read_keys.max_discount_percent (padrão 20%).
-- Só a função crm-read (service_role) chama estas funções.

ALTER TABLE public.crm_read_keys ADD COLUMN IF NOT EXISTS operator_phones text[] NOT NULL DEFAULT '{}';
ALTER TABLE public.crm_read_keys ADD COLUMN IF NOT EXISTS max_discount_percent numeric NOT NULL DEFAULT 20
    CHECK (max_discount_percent >= 0 AND max_discount_percent <= 90);

ALTER TABLE public.crm_read_keys DROP CONSTRAINT IF EXISTS crm_read_keys_scopes_check;
ALTER TABLE public.crm_read_keys ADD CONSTRAINT crm_read_keys_scopes_check
    CHECK (cardinality(scopes) > 0 AND scopes <@ ARRAY[
        'proposals:read', 'agenda:read', 'clients:create',
        'agenda:create', 'proposals:write', 'proposals:send'
    ]::text[]);

CREATE TABLE IF NOT EXISTS public.crm_team_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key_id uuid NOT NULL REFERENCES public.crm_read_keys(id) ON DELETE CASCADE,
    organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
    action text NOT NULL,
    operator_phone text NOT NULL,
    client_id integer,
    reference text,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS crm_team_actions_key_time ON public.crm_team_actions (key_id, created_at DESC);
ALTER TABLE public.crm_team_actions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.crm_team_actions FROM PUBLIC, anon, authenticated;

-- Telefone comparável: 55 + DDD + 8 últimos dígitos (ignora o nono dígito).
CREATE OR REPLACE FUNCTION public.crm_phone_key(p_phone text)
RETURNS text LANGUAGE sql IMMUTABLE SET search_path = public AS $$
    WITH d AS (SELECT ltrim(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), '0') AS v),
    n AS (SELECT CASE WHEN v ~ '^[0-9]{10,11}$' THEN '55' || v ELSE v END AS v FROM d)
    SELECT CASE
        WHEN v ~ '^55[0-9]{11}$' THEN substr(v, 1, 4) || right(v, 8)
        WHEN v ~ '^55[0-9]{10}$' THEN v
        WHEN v ~ '^[0-9]{12,15}$' THEN v
    END FROM n;
$$;

-- Confere chave, permissão, número da equipe e limite. Devolve o dono da empresa.
CREATE OR REPLACE FUNCTION public.crm_team_guard(p_key_id uuid, p_organization_id uuid, p_scope text, p_operator text)
RETURNS uuid LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_phones text[];
    v_owner uuid;
BEGIN
    SELECT k.operator_phones INTO v_phones FROM public.crm_read_keys k
     WHERE k.id = p_key_id AND k.organization_id = p_organization_id
       AND k.enabled AND k.revoked_at IS NULL AND (k.expires_at IS NULL OR k.expires_at > now())
       AND p_scope = ANY (k.scopes);
    IF NOT FOUND THEN RAISE EXCEPTION 'CRM:permissao'; END IF;

    IF public.crm_phone_key(p_operator) IS NULL OR NOT EXISTS (
        SELECT 1 FROM unnest(v_phones) phone WHERE public.crm_phone_key(phone) = public.crm_phone_key(p_operator)
    ) THEN RAISE EXCEPTION 'CRM:operador'; END IF;

    IF (SELECT count(*) FROM public.crm_team_actions a
         WHERE a.key_id = p_key_id AND a.created_at > now() - interval '1 hour') >= 60 THEN
        RAISE EXCEPTION 'CRM:limite';
    END IF;

    SELECT owner_id INTO v_owner FROM public.organizations WHERE id = p_organization_id;
    IF v_owner IS NULL THEN RAISE EXCEPTION 'CRM:permissao'; END IF;
    RETURN v_owner;
END;
$$;

-- Usuários da empresa (dono, equipe ativa e perfis ligados).
CREATE OR REPLACE FUNCTION public.crm_company_users(p_organization_id uuid)
RETURNS SETOF uuid LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT owner_id FROM public.organizations WHERE id = p_organization_id
    UNION SELECT m.user_id FROM public.organization_members m WHERE m.organization_id = p_organization_id AND m.status = 'active'
    UNION SELECT p.id FROM public.profiles p WHERE p.organization_id = p_organization_id;
$$;

-- Cliente da empresa pelo telefone (com/sem nono dígito) ou pelo número do cadastro.
CREATE OR REPLACE FUNCTION public.crm_find_client(p_organization_id uuid, p_phone text, p_client_id integer)
RETURNS TABLE (client_id integer, client_name text)
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_found jsonb;
BEGIN
    IF p_client_id IS NOT NULL THEN
        RETURN QUERY SELECT c.id, c.nome FROM public.clients c
         WHERE c.id = p_client_id
           AND (c.organization_id = p_organization_id
                OR (c.organization_id IS NULL AND c.user_id IN (SELECT public.crm_company_users(p_organization_id))));
        RETURN;
    END IF;
    IF p_phone IS NULL THEN RETURN; END IF;
    v_found := public.whatsapp_bridge_client_phones(p_organization_id, ARRAY[p_phone]) -> p_phone;
    IF v_found IS NOT NULL THEN
        RETURN QUERY SELECT (v_found->>'client_id')::integer, v_found->>'name';
    END IF;
END;
$$;

-- Catálogo de películas da empresa.
CREATE OR REPLACE FUNCTION public.crm_company_films(p_organization_id uuid)
RETURNS TABLE (nome text, preco numeric, mao_de_obra numeric, pinned boolean)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    SELECT DISTINCT ON (lower(trim(f.nome))) f.nome, f.preco, f.mao_de_obra, coalesce(f.pinned, false)
      FROM public.films f
     WHERE f.user_id IN (SELECT public.crm_company_users(p_organization_id))
       AND coalesce(trim(f.nome), '') <> ''
     ORDER BY lower(trim(f.nome)), (f.user_id = (SELECT owner_id FROM public.organizations WHERE id = p_organization_id)) DESC;
$$;

-- Total de uma opção como o app calcula no modo padrão (por m², preço do catálogo,
-- área de cada medida arredondada em 2 casas, desconto geral em %).
CREATE OR REPLACE FUNCTION public.crm_option_totals(p_organization_id uuid, p_measurements jsonb, p_discount_percent numeric)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
    WITH items AS (
        SELECT m.value AS item,
               coalesce(nullif(replace(m.value->>'largura', ',', '.'), '')::numeric, 0) AS largura,
               coalesce(nullif(replace(m.value->>'altura', ',', '.'), '')::numeric, 0) AS altura,
               coalesce(nullif(m.value->>'quantidade', '')::numeric, 0) AS quantidade
          FROM jsonb_array_elements(coalesce(p_measurements, '[]'::jsonb)) m
         WHERE jsonb_typeof(m.value) = 'object' AND coalesce((m.value->>'active')::boolean, true)
    ), priced AS (
        SELECT i.*, round(i.largura * i.altura * i.quantidade, 2) AS m2,
               (SELECT CASE WHEN coalesce(f.preco, 0) > 0 THEN f.preco ELSE coalesce(f.mao_de_obra, 0) END
                  FROM public.crm_company_films(p_organization_id) f
                 WHERE f.nome = i.item->>'pelicula' LIMIT 1) AS price
          FROM items i
    ), sums AS (
        SELECT coalesce(sum(m2), 0) AS m2, coalesce(sum(m2 * coalesce(price, 0)), 0) AS subtotal,
               bool_or(coalesce(price, 0) = 0) AS missing
          FROM priced
    )
    SELECT jsonb_build_object(
        'm2', round(m2, 2),
        'subtotal', round(subtotal, 2),
        'desconto', round(subtotal * greatest(0, coalesce(p_discount_percent, 0)) / 100, 2),
        'total', round(subtotal, 2) - round(subtotal * greatest(0, coalesce(p_discount_percent, 0)) / 100, 2),
        'sem_preco', coalesce(missing, false)
    ) FROM sums;
$$;

-- 1) Marcar na agenda.
CREATE OR REPLACE FUNCTION public.crm_agenda_create(
    p_key_id uuid, p_organization_id uuid, p_operator text,
    p_phone text, p_client_id integer,
    p_start timestamptz, p_end timestamptz, p_type text, p_notes text
) RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_owner uuid;
    v_client record;
    v_capacity integer;
    v_busy integer;
    v_id integer;
    v_type text := CASE p_type WHEN 'instalacao' THEN 'instalacao' ELSE 'consulta' END;
BEGIN
    v_owner := public.crm_team_guard(p_key_id, p_organization_id, 'agenda:create', p_operator);

    IF p_start IS NULL OR p_end IS NULL OR p_end <= p_start OR p_end - p_start > interval '12 hours' THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'horario_invalido');
    END IF;
    IF p_start < now() - interval '1 hour' OR p_start > now() + interval '180 days' THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'data_fora_do_prazo');
    END IF;

    SELECT * INTO v_client FROM public.crm_find_client(p_organization_id, p_phone, p_client_id) LIMIT 1;
    IF v_client.client_id IS NULL THEN RETURN jsonb_build_object('ok', false, 'motivo', 'cliente_nao_encontrado'); END IF;

    -- Mesma regra do app: atendimentos simultâneos = tamanho da equipe ativa (mínimo 1).
    SELECT greatest(1, count(*)) INTO v_capacity FROM public.organization_members m
     WHERE m.organization_id = p_organization_id AND m.status = 'active';
    SELECT count(*) INTO v_busy FROM public.agendamentos a
     WHERE a.user_id IN (SELECT public.crm_company_users(p_organization_id))
       AND coalesce(a.start, a.start_time) < p_end
       AND coalesce(a."end", a.end_time, coalesce(a.start, a.start_time) + interval '1 hour') > p_start
       AND coalesce(a.service_status, 'scheduled') NOT IN ('cancelled', 'no_show');
    IF v_busy >= v_capacity THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'conflito');
    END IF;

    INSERT INTO public.agendamentos (user_id, client_id, client_name, cliente_nome, start, "end", start_time, end_time,
                                     notes, service_status, event_type, title, pdf_ids)
    VALUES (v_owner, v_client.client_id, v_client.client_name, v_client.client_name, p_start, p_end, p_start, p_end,
            nullif(left(btrim(coalesce(p_notes, '')), 1000), ''), 'scheduled', v_type,
            CASE v_type WHEN 'instalacao' THEN 'Instalação' ELSE 'Visita de medição' END || ' (WhatsApp)', '{}')
    RETURNING id INTO v_id;

    INSERT INTO public.crm_team_actions (key_id, organization_id, action, operator_phone, client_id, reference)
    VALUES (p_key_id, p_organization_id, 'agenda_criar', public.crm_phone_key(p_operator), v_client.client_id, v_id::text);

    RETURN jsonb_build_object('ok', true, 'agenda_id', v_id, 'client_id', v_client.client_id, 'client_name', v_client.client_name, 'tipo', v_type);
END;
$$;

-- 2) Calcular / recalcular as opções da proposta (não envia nada ao cliente).
-- As opções da IA se chamam "<película> (WhatsApp)"; são trocadas a cada cálculo.
-- As opções que a equipe montou no app ficam como estão.
CREATE OR REPLACE FUNCTION public.crm_proposal_generate(
    p_key_id uuid, p_organization_id uuid, p_operator text,
    p_phone text, p_client_id integer, p_films text[], p_discount_percent numeric
) RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_client record;
    v_max numeric;
    v_state record;
    v_base jsonb;
    v_films text[];
    v_unknown text[];
    v_options jsonb := '[]'::jsonb;
    v_result jsonb := '[]'::jsonb;
    v_film text;
    v_measurements jsonb;
    v_option jsonb;
    v_ids bigint := (extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    v_discount numeric := coalesce(p_discount_percent, 0);
    v_snapshot jsonb;
    v_revision bigint;
    i integer := 0;
BEGIN
    PERFORM public.crm_team_guard(p_key_id, p_organization_id, 'proposals:write', p_operator);
    SELECT max_discount_percent INTO v_max FROM public.crm_read_keys WHERE id = p_key_id;
    IF v_discount < 0 OR v_discount > v_max THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'desconto_acima_do_limite', 'limite', v_max);
    END IF;

    SELECT * INTO v_client FROM public.crm_find_client(p_organization_id, p_phone, p_client_id) LIMIT 1;
    IF v_client.client_id IS NULL THEN RETURN jsonb_build_object('ok', false, 'motivo', 'cliente_nao_encontrado'); END IF;

    SELECT s.snapshot, s.revision INTO v_state FROM public.proposal_option_states s WHERE s.client_id = v_client.client_id FOR UPDATE;
    IF v_state.snapshot IS NULL OR jsonb_typeof(v_state.snapshot) <> 'array' THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'sem_medidas');
    END IF;

    -- Medidas base: o rascunho do WhatsApp; senão a primeira opção da IA; senão a primeira com medidas.
    SELECT o.value->'measurements' INTO v_base
      FROM jsonb_array_elements(v_state.snapshot) WITH ORDINALITY o
     WHERE jsonb_typeof(o.value->'measurements') = 'array' AND jsonb_array_length(o.value->'measurements') > 0
     ORDER BY (o.value->>'name' = 'WhatsApp (rascunho)') DESC, (o.value->>'name' LIKE '% (WhatsApp)') DESC, o.ordinality
     LIMIT 1;
    IF v_base IS NULL THEN RETURN jsonb_build_object('ok', false, 'motivo', 'sem_medidas'); END IF;

    -- Películas: as pedidas; senão as das opções da IA já calculadas; senão a das medidas.
    v_films := (SELECT array_agg(DISTINCT btrim(f)) FROM unnest(coalesce(p_films, '{}')) f WHERE btrim(f) <> '');
    IF v_films IS NULL THEN
        v_films := (SELECT array_agg(DISTINCT o.value->'measurements'->0->>'pelicula')
                      FROM jsonb_array_elements(v_state.snapshot) o WHERE o.value->>'name' LIKE '% (WhatsApp)');
    END IF;
    IF v_films IS NULL THEN
        v_films := (SELECT array_agg(DISTINCT m.value->>'pelicula') FROM jsonb_array_elements(v_base) m
                     WHERE coalesce(m.value->>'pelicula', 'Nenhuma') <> 'Nenhuma');
    END IF;
    IF v_films IS NULL OR cardinality(v_films) = 0 THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'escolha_peliculas',
            'disponiveis', (SELECT coalesce(jsonb_agg(nome ORDER BY pinned DESC, nome), '[]') FROM (SELECT nome, pinned FROM public.crm_company_films(p_organization_id) LIMIT 40) c));
    END IF;
    IF cardinality(v_films) > 4 THEN RETURN jsonb_build_object('ok', false, 'motivo', 'no_maximo_4_peliculas'); END IF;

    -- Nome exato do catálogo (sem diferença de maiúsculas).
    v_unknown := (SELECT array_agg(f) FROM unnest(v_films) f
                   WHERE NOT EXISTS (SELECT 1 FROM public.crm_company_films(p_organization_id) c WHERE lower(trim(c.nome)) = lower(f)));
    IF v_unknown IS NOT NULL THEN
        RETURN jsonb_build_object('ok', false, 'motivo', 'pelicula_desconhecida', 'desconhecidas', to_jsonb(v_unknown),
            'disponiveis', (SELECT coalesce(jsonb_agg(nome ORDER BY pinned DESC, nome), '[]') FROM (SELECT nome, pinned FROM public.crm_company_films(p_organization_id) LIMIT 40) c));
    END IF;
    v_films := (SELECT array_agg(c.nome ORDER BY ord) FROM unnest(v_films) WITH ORDINALITY f(name, ord)
                  JOIN public.crm_company_films(p_organization_id) c ON lower(trim(c.nome)) = lower(f.name));

    FOREACH v_film IN ARRAY v_films LOOP
        i := i + 1;
        SELECT jsonb_agg(m.value || jsonb_build_object('id', v_ids + i * 100 + m.ordinality, 'pelicula', v_film) ORDER BY m.ordinality)
          INTO v_measurements FROM jsonb_array_elements(v_base) WITH ORDINALITY m;
        v_option := jsonb_build_object(
            'id', v_ids + i,
            'name', left(v_film, 60) || ' (WhatsApp)',
            'measurements', v_measurements,
            'generalDiscount', CASE WHEN v_discount > 0
                THEN jsonb_build_object('value', v_discount::text, 'type', 'percentage', 'discountValue', v_discount::text, 'discountType', 'percentage')
                ELSE jsonb_build_object('value', '0', 'type', 'percentage') END
        );
        v_options := v_options || jsonb_build_array(v_option);
        v_result := v_result || jsonb_build_array(jsonb_build_object('nome', v_option->>'name', 'pelicula', v_film, 'desconto_percentual', v_discount)
            || public.crm_option_totals(p_organization_id, v_measurements, v_discount));
    END LOOP;

    v_snapshot := coalesce((SELECT jsonb_agg(o.value ORDER BY o.ordinality) FROM jsonb_array_elements(v_state.snapshot) WITH ORDINALITY o
                             WHERE coalesce(o.value->>'name', '') NOT LIKE '% (WhatsApp)'), '[]'::jsonb) || v_options;
    v_revision := v_state.revision + 1;

    UPDATE public.proposal_option_states
       SET snapshot = v_snapshot, revision = v_revision, updated_at = now(), updated_by = NULL, updated_device_id = 'whatsapp-ia'
     WHERE client_id = v_client.client_id;
    INSERT INTO public.proposal_option_history (client_id, organization_id, revision, snapshot, created_at, created_by, source_device_id)
    VALUES (v_client.client_id, p_organization_id, v_revision, v_snapshot, now(), NULL, 'whatsapp-ia')
    ON CONFLICT (client_id, revision) DO NOTHING;

    INSERT INTO public.crm_team_actions (key_id, organization_id, action, operator_phone, client_id, reference)
    VALUES (p_key_id, p_organization_id, 'proposta_gerar', public.crm_phone_key(p_operator), v_client.client_id, v_revision::text);

    RETURN jsonb_build_object('ok', true, 'client_id', v_client.client_id, 'client_name', v_client.client_name, 'opcoes', v_result);
END;
$$;

-- 3) Ver as opções calculadas e os links já enviados (só leitura).
CREATE OR REPLACE FUNCTION public.crm_proposal_status(p_organization_id uuid, p_phone text, p_client_id integer)
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_client record;
    v_snapshot jsonb;
BEGIN
    SELECT * INTO v_client FROM public.crm_find_client(p_organization_id, p_phone, p_client_id) LIMIT 1;
    IF v_client.client_id IS NULL THEN RETURN jsonb_build_object('ok', false, 'motivo', 'cliente_nao_encontrado'); END IF;
    SELECT s.snapshot INTO v_snapshot FROM public.proposal_option_states s WHERE s.client_id = v_client.client_id;

    RETURN jsonb_build_object(
        'ok', true,
        'client_id', v_client.client_id,
        'client_name', v_client.client_name,
        'opcoes', (SELECT coalesce(jsonb_agg(jsonb_build_object(
                        'nome', o.value->>'name',
                        'da_ia', coalesce(o.value->>'name', '') LIKE '% (WhatsApp)',
                        'rascunho', o.value->>'name' = 'WhatsApp (rascunho)',
                        'peliculas', (SELECT jsonb_agg(DISTINCT m.value->>'pelicula') FROM jsonb_array_elements(o.value->'measurements') m),
                        'desconto_percentual', CASE WHEN coalesce(o.value->'generalDiscount'->>'discountType', o.value->'generalDiscount'->>'type') = 'percentage'
                            THEN coalesce(nullif(replace(coalesce(o.value->'generalDiscount'->>'discountValue', o.value->'generalDiscount'->>'value'), ',', '.'), '')::numeric, 0) END
                    ) || public.crm_option_totals(p_organization_id, o.value->'measurements',
                            CASE WHEN coalesce(o.value->'generalDiscount'->>'discountType', o.value->'generalDiscount'->>'type') = 'percentage'
                            THEN coalesce(nullif(replace(coalesce(o.value->'generalDiscount'->>'discountValue', o.value->'generalDiscount'->>'value'), ',', '.'), '')::numeric, 0) ELSE 0 END)
                    ORDER BY o.ordinality), '[]'::jsonb)
                   FROM jsonb_array_elements(CASE WHEN jsonb_typeof(v_snapshot) = 'array' THEN v_snapshot ELSE '[]'::jsonb END) WITH ORDINALITY o
                  WHERE jsonb_typeof(o.value->'measurements') = 'array'),
        'links', (SELECT coalesce(jsonb_agg(jsonb_build_object(
                        'token', p.token, 'status', p.status, 'expira_em', p.expires_at, 'criado_em', p.created_at,
                        'visualizacoes', p.view_count, 'ultima_visualizacao', p.last_viewed_at) ORDER BY p.created_at DESC), '[]'::jsonb)
                    FROM (SELECT * FROM public.proposal_portals pp
                           WHERE pp.client_id = v_client.client_id AND pp.organization_id = p_organization_id AND pp.status <> 'revoked'
                           ORDER BY pp.created_at DESC LIMIT 5) p)
    );
END;
$$;

-- 4) Enviar: cria as propostas salvas (sem PDF) e o link. Só com o OK da equipe.
CREATE OR REPLACE FUNCTION public.crm_proposal_send(
    p_key_id uuid, p_organization_id uuid, p_operator text,
    p_phone text, p_client_id integer, p_option_names text[], p_valid_days integer
) RETURNS jsonb LANGUAGE plpgsql VOLATILE SECURITY DEFINER SET search_path = public AS $$
DECLARE
    v_owner uuid;
    v_client record;
    v_snapshot jsonb;
    v_expires timestamptz := (date_trunc('day', now() AT TIME ZONE 'America/Sao_Paulo')
                              + make_interval(days => greatest(1, least(30, coalesce(p_valid_days, 7))))
                              + interval '23 hours 59 minutes 59 seconds') AT TIME ZONE 'America/Sao_Paulo';
    v_portal public.proposal_portals%ROWTYPE;
    v_option record;
    v_discount numeric;
    v_totals jsonb;
    v_pdf_id integer;
    v_out jsonb := '[]'::jsonb;
    v_pos integer := 0;
BEGIN
    v_owner := public.crm_team_guard(p_key_id, p_organization_id, 'proposals:send', p_operator);
    SELECT * INTO v_client FROM public.crm_find_client(p_organization_id, p_phone, p_client_id) LIMIT 1;
    IF v_client.client_id IS NULL THEN RETURN jsonb_build_object('ok', false, 'motivo', 'cliente_nao_encontrado'); END IF;
    SELECT s.snapshot INTO v_snapshot FROM public.proposal_option_states s WHERE s.client_id = v_client.client_id;
    IF jsonb_typeof(v_snapshot) <> 'array' THEN v_snapshot := '[]'::jsonb; END IF;

    FOR v_option IN
        SELECT o.value, o.ordinality FROM jsonb_array_elements(v_snapshot) WITH ORDINALITY o
         WHERE jsonb_typeof(o.value->'measurements') = 'array' AND jsonb_array_length(o.value->'measurements') > 0
           AND o.value->>'name' IS DISTINCT FROM 'WhatsApp (rascunho)'
           AND CASE WHEN coalesce(cardinality(p_option_names), 0) > 0
                    THEN lower(o.value->>'name') IN (SELECT lower(btrim(n)) FROM unnest(p_option_names) n)
                    ELSE coalesce(o.value->>'name', '') LIKE '% (WhatsApp)' END
         ORDER BY o.ordinality
         LIMIT 6
    LOOP
        v_discount := CASE WHEN coalesce(v_option.value->'generalDiscount'->>'discountType', v_option.value->'generalDiscount'->>'type') = 'percentage'
            THEN coalesce(nullif(replace(coalesce(v_option.value->'generalDiscount'->>'discountValue', v_option.value->'generalDiscount'->>'value'), ',', '.'), '')::numeric, 0) ELSE 0 END;
        v_totals := public.crm_option_totals(p_organization_id, v_option.value->'measurements', v_discount);
        IF (v_totals->>'sem_preco')::boolean OR (v_totals->>'total')::numeric <= 0 THEN
            RETURN jsonb_build_object('ok', false, 'motivo', 'opcao_sem_preco', 'opcao', v_option.value->>'name');
        END IF;

        IF v_portal.id IS NULL THEN
            INSERT INTO public.proposal_portals (organization_id, client_id, created_by, expires_at)
            VALUES (p_organization_id, v_client.client_id, v_owner, v_expires)
            RETURNING * INTO v_portal;
        END IF;

        INSERT INTO public.saved_pdfs (user_id, client_id, client_name, date, expiration_date, total_preco, total_m2, subtotal,
                                       general_discount_amount, general_discount, nome_arquivo, measurements, status,
                                       proposal_option_name, proposal_option_id)
        VALUES (v_owner, v_client.client_id, v_client.client_name, now(), v_expires, (v_totals->>'total')::numeric,
                (v_totals->>'m2')::numeric, (v_totals->>'subtotal')::numeric, (v_totals->>'desconto')::numeric,
                v_option.value->'generalDiscount',
                left('Orcamento ' || coalesce(v_client.client_name, 'cliente') || ' - ' || coalesce(v_option.value->>'name', 'opcao'), 150) || '.pdf',
                v_option.value->'measurements', 'pending', v_option.value->>'name',
                CASE WHEN (v_option.value->>'id') ~ '^[0-9]{1,18}$' THEN (v_option.value->>'id')::bigint END)
        RETURNING id INTO v_pdf_id;

        INSERT INTO public.proposal_portal_items (portal_id, saved_pdf_id, position, condition_original_value, condition_final_value,
                                                  condition_discount_amount, condition_discount_percent, condition_expires_at, condition_updated_at)
        VALUES (v_portal.id, v_pdf_id, v_pos,
                CASE WHEN v_discount > 0 THEN (v_totals->>'subtotal')::numeric END,
                CASE WHEN v_discount > 0 THEN (v_totals->>'total')::numeric END,
                CASE WHEN v_discount > 0 THEN (v_totals->>'desconto')::numeric END,
                CASE WHEN v_discount > 0 THEN v_discount END,
                CASE WHEN v_discount > 0 THEN v_expires END,
                CASE WHEN v_discount > 0 THEN now() END);
        v_pos := v_pos + 1;
        v_out := v_out || jsonb_build_array(jsonb_build_object('nome', v_option.value->>'name', 'proposta_id', v_pdf_id) || v_totals);
    END LOOP;

    IF v_portal.id IS NULL THEN RETURN jsonb_build_object('ok', false, 'motivo', 'nenhuma_opcao_para_enviar'); END IF;

    INSERT INTO public.crm_team_actions (key_id, organization_id, action, operator_phone, client_id, reference)
    VALUES (p_key_id, p_organization_id, 'proposta_enviar', public.crm_phone_key(p_operator), v_client.client_id, v_portal.id::text);

    RETURN jsonb_build_object('ok', true, 'client_id', v_client.client_id, 'client_name', v_client.client_name,
        'token', v_portal.token, 'expira_em', v_portal.expires_at, 'opcoes', v_out);
END;
$$;

