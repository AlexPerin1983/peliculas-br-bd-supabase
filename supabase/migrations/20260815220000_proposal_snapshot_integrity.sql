-- Salvamento seguro de medidas entre aparelhos.
-- Cada cliente possui uma revisão canônica, histórico recuperável e escrita
-- atômica com comparação de versão.

CREATE TABLE IF NOT EXISTS public.proposal_option_states (
    client_id bigint PRIMARY KEY REFERENCES public.clients(id) ON DELETE CASCADE,
    organization_id uuid,
    revision bigint NOT NULL DEFAULT 0 CHECK (revision >= 0),
    snapshot jsonb NOT NULL DEFAULT '[]'::jsonb CHECK (jsonb_typeof(snapshot) = 'array'),
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by uuid,
    updated_device_id text
);

CREATE TABLE IF NOT EXISTS public.proposal_option_history (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id bigint NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
    organization_id uuid,
    revision bigint NOT NULL,
    snapshot jsonb NOT NULL CHECK (jsonb_typeof(snapshot) = 'array'),
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by uuid,
    source_device_id text,
    UNIQUE (client_id, revision)
);

CREATE INDEX IF NOT EXISTS proposal_option_history_client_created_idx
    ON public.proposal_option_history (client_id, created_at DESC);

ALTER TABLE public.proposal_option_states ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.proposal_option_history ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.can_access_proposal_client(target_client_id bigint)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, auth
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.clients client
        LEFT JOIN public.profiles current_profile
          ON current_profile.id = auth.uid()
        WHERE client.id = target_client_id
          AND (
              client.user_id = auth.uid()
              OR (
                  client.organization_id IS NOT NULL
                  AND client.organization_id = current_profile.organization_id
              )
              OR EXISTS (
                  SELECT 1
                  FROM public.organizations organization
                  JOIN public.organization_members member
                    ON member.organization_id = organization.id
                  WHERE organization.owner_id = client.user_id
                    AND member.user_id = auth.uid()
                    AND member.status = 'active'
              )
          )
    );
$$;

