-- Clientes antigos podem continuar alguns minutos com uma versão em cache do
-- PWA. Essa função combina as inclusões legadas com a fotografia canônica em
-- vez de permitir que um snapshot menor apague medidas já recebidas.
CREATE OR REPLACE FUNCTION public.merge_legacy_proposal_snapshots(
    canonical_snapshot jsonb,
    legacy_snapshot jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    canonical_option jsonb;
    legacy_option jsonb;
    canonical_measurement jsonb;
    merged_option jsonb;
    merged_measurements jsonb;
    result_snapshot jsonb := '[]'::jsonb;
BEGIN
    IF jsonb_typeof(canonical_snapshot) <> 'array' THEN
        canonical_snapshot := '[]'::jsonb;
    END IF;
    IF jsonb_typeof(legacy_snapshot) <> 'array' THEN
        legacy_snapshot := '[]'::jsonb;
    END IF;

    FOR legacy_option IN SELECT value FROM jsonb_array_elements(legacy_snapshot)
    LOOP
        SELECT value INTO canonical_option
        FROM jsonb_array_elements(canonical_snapshot)
        WHERE lower(trim(value->>'name')) = lower(trim(legacy_option->>'name'))
        LIMIT 1;

        merged_measurements := COALESCE(legacy_option->'measurements', '[]'::jsonb);

        IF canonical_option IS NOT NULL THEN
            FOR canonical_measurement IN
                SELECT value
                FROM jsonb_array_elements(COALESCE(canonical_option->'measurements', '[]'::jsonb))
            LOOP
                IF NOT EXISTS (
                    SELECT 1
                    FROM jsonb_array_elements(merged_measurements) legacy_measurement
                    WHERE legacy_measurement->>'id' = canonical_measurement->>'id'
                ) THEN
                    merged_measurements := merged_measurements || jsonb_build_array(canonical_measurement);
                END IF;
            END LOOP;
        END IF;

        merged_option := jsonb_set(legacy_option, '{measurements}', merged_measurements, true);
        result_snapshot := result_snapshot || jsonb_build_array(merged_option);
        canonical_option := NULL;
    END LOOP;

    FOR canonical_option IN SELECT value FROM jsonb_array_elements(canonical_snapshot)
    LOOP
        IF NOT EXISTS (
            SELECT 1
            FROM jsonb_array_elements(legacy_snapshot) legacy_candidate
            WHERE lower(trim(legacy_candidate->>'name')) = lower(trim(canonical_option->>'name'))
        ) THEN
            result_snapshot := result_snapshot || jsonb_build_array(canonical_option);
        END IF;
    END LOOP;

    RETURN result_snapshot;
END;
$$;

CREATE OR REPLACE FUNCTION public.capture_legacy_proposal_snapshot()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    affected_client_id bigint;
    current_revision bigint;
    current_snapshot jsonb;
    legacy_snapshot jsonb;
    merged_snapshot jsonb;
    current_org_id uuid;
BEGIN
    IF current_setting('app.proposal_snapshot_rpc', true) = '1' THEN
        RETURN NULL;
    END IF;

    FOR affected_client_id IN SELECT DISTINCT client_id FROM new_proposal_rows
    LOOP
        PERFORM pg_advisory_xact_lock(affected_client_id);

        SELECT state.revision, state.snapshot, state.organization_id
          INTO current_revision, current_snapshot, current_org_id
        FROM public.proposal_option_states state
        WHERE state.client_id = affected_client_id
        FOR UPDATE;

        SELECT COALESCE(
            jsonb_agg(
                jsonb_build_object(
                    'id', proposal.id,
                    'name', proposal.name,
                    'measurements', COALESCE(proposal.measurements, '[]'::jsonb),
                    'generalDiscount', COALESCE(proposal.general_discount, '{}'::jsonb)
                ) ORDER BY proposal.id
            ),
            '[]'::jsonb
        )
        INTO legacy_snapshot
        FROM public.proposal_options proposal
        WHERE proposal.client_id = affected_client_id;

        merged_snapshot := public.merge_legacy_proposal_snapshots(
            COALESCE(current_snapshot, '[]'::jsonb),
            legacy_snapshot
        );
        current_revision := COALESCE(current_revision, 0) + 1;

        INSERT INTO public.proposal_option_states (
            client_id, organization_id, revision, snapshot,
            updated_at, updated_by, updated_device_id
        )
        VALUES (
            affected_client_id,
            COALESCE(
                current_org_id,
                (SELECT organization_id FROM public.profiles WHERE id = auth.uid())
            ),
            current_revision,
            merged_snapshot,
            now(),
            auth.uid(),
            'legacy-client'
        )
        ON CONFLICT (client_id) DO UPDATE SET
            revision = EXCLUDED.revision,
            snapshot = EXCLUDED.snapshot,
            updated_at = EXCLUDED.updated_at,
            updated_by = EXCLUDED.updated_by,
            updated_device_id = EXCLUDED.updated_device_id;

        INSERT INTO public.proposal_option_history (
            client_id, organization_id, revision, snapshot,
            created_at, created_by, source_device_id
        )
        SELECT
            affected_client_id,
            organization_id,
            revision,
            snapshot,
            updated_at,
            updated_by,
            updated_device_id
        FROM public.proposal_option_states
        WHERE client_id = affected_client_id
        ON CONFLICT (client_id, revision) DO NOTHING;
    END LOOP;

    RETURN NULL;
END;
$$;

