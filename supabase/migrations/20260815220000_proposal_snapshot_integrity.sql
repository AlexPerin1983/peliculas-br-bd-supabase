INSERT INTO public.proposal_option_states (
    client_id,
    organization_id,
    revision,
    snapshot,
    updated_at,
    updated_by,
    updated_device_id
)
SELECT
    proposal.client_id,
    (array_agg(proposal.organization_id) FILTER (WHERE proposal.organization_id IS NOT NULL))[1],
    1,
    jsonb_agg(
        jsonb_build_object(
            'id', proposal.id,
            'name', proposal.name,
            'measurements', COALESCE(proposal.measurements, '[]'::jsonb),
            'generalDiscount', COALESCE(proposal.general_discount, '{}'::jsonb)
        )
        ORDER BY proposal.id
    ),
    max(proposal.created_at),
    (array_agg(proposal.user_id) FILTER (WHERE proposal.user_id IS NOT NULL))[1],
    'migration'
FROM public.proposal_options proposal
GROUP BY proposal.client_id
ON CONFLICT (client_id) DO NOTHING;

