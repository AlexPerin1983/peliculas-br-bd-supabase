        VALUES (
            p_client_id, current_org_id, 0, current_snapshot,
            now(), current_user_id, p_device_id
        );
    END IF;

    IF current_org_id IS NULL THEN
        SELECT organization_id INTO current_org_id
        FROM public.profiles
        WHERE id = current_user_id;
    END IF;

    IF COALESCE(p_expected_revision, 0) <> current_revision THEN
        RETURN jsonb_build_object(
            'status', 'conflict',
            'revision', current_revision,
            'snapshot', current_snapshot
        );
    END IF;

    IF jsonb_array_length(p_operations) = 0 THEN
        RETURN jsonb_build_object(
            'status', 'saved',
            'revision', current_revision,
            'snapshot', current_snapshot,
            'operationCount', 0
        );
    END IF;

    next_snapshot := public.apply_proposal_operations(current_snapshot, p_operations);
    next_revision := current_revision + 1;

    UPDATE public.proposal_option_states
    SET revision = next_revision,
        snapshot = next_snapshot,
        organization_id = COALESCE(organization_id, current_org_id),
        updated_at = now(),
        updated_by = current_user_id,
        updated_device_id = p_device_id
    WHERE client_id = p_client_id;

    INSERT INTO public.proposal_option_history (
        client_id, organization_id, revision, snapshot,
        created_at, created_by, source_device_id
    )
    VALUES (
        p_client_id, current_org_id, next_revision, next_snapshot,
        now(), current_user_id, p_device_id
    )
    ON CONFLICT (client_id, revision) DO NOTHING;

    -- Compatibilidade temporária com telas antigas do PWA.
    PERFORM set_config('app.proposal_snapshot_rpc', '1', true);

    DELETE FROM public.proposal_options
    WHERE client_id = p_client_id;

    FOR option_value IN SELECT value FROM jsonb_array_elements(next_snapshot)
    LOOP
        INSERT INTO public.proposal_options (
            user_id,
            organization_id,
            client_id,
            name,
            measurements,
            general_discount
        )
        VALUES (
            current_user_id,
            current_org_id,
            p_client_id,
            COALESCE(option_value->>'name', 'Opcao 1'),
            COALESCE(option_value->'measurements', '[]'::jsonb),
            COALESCE(option_value->'generalDiscount', '{}'::jsonb)
        );
    END LOOP;

    UPDATE public.clients
    SET last_updated = now()
    WHERE id = p_client_id;

    RETURN jsonb_build_object(
        'status', 'saved',
        'revision', next_revision,
        'snapshot', next_snapshot,
        'operationCount', jsonb_array_length(p_operations)
    );
END;
$$;

