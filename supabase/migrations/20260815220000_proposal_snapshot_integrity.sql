CREATE OR REPLACE FUNCTION public.save_proposal_options_snapshot(
    p_client_id bigint,
    p_snapshot jsonb,
    p_expected_revision bigint,
    p_device_id text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, auth
AS $$
DECLARE
    current_revision bigint;
    current_snapshot jsonb;
    next_revision bigint;
    current_user_id uuid := auth.uid();
    current_org_id uuid;
    option_value jsonb;
BEGIN
    IF current_user_id IS NULL THEN
        RAISE EXCEPTION 'Sessao nao autenticada';
    END IF;

    IF NOT public.can_access_proposal_client(p_client_id) THEN
        RAISE EXCEPTION 'Cliente nao autorizado';
    END IF;

    IF jsonb_typeof(p_snapshot) <> 'array' THEN
        RAISE EXCEPTION 'Snapshot de medidas deve ser um array';
    END IF;

    PERFORM pg_advisory_xact_lock(p_client_id);

    SELECT state.revision, state.snapshot, state.organization_id
      INTO current_revision, current_snapshot, current_org_id
    FROM public.proposal_option_states state
    WHERE state.client_id = p_client_id
    FOR UPDATE;

    IF NOT FOUND THEN
        current_revision := 0;
        current_snapshot := '[]'::jsonb;
        SELECT organization_id INTO current_org_id
        FROM public.profiles
        WHERE id = current_user_id;

        INSERT INTO public.proposal_option_states (
            client_id, organization_id, revision, snapshot,
            updated_at, updated_by, updated_device_id
        )
        VALUES (
            p_client_id, current_org_id, 0, current_snapshot,
            now(), current_user_id, p_device_id
        );
    END IF;

    IF current_org_id IS NULL THEN
        SELECT organization_id INTO current_org_id
        FROM public.profiles
        WHERE id = current_user_id;
    END IF;

    IF COALESCE(p_expected_revision, 0) <> current_revision THEN
        RETURN jsonb_build_object(
            'status', 'conflict',
            'revision', current_revision,
            'snapshot', current_snapshot
        );
    END IF;

    next_revision := current_revision + 1;

    UPDATE public.proposal_option_states
    SET revision = next_revision,
        snapshot = p_snapshot,
        organization_id = COALESCE(organization_id, current_org_id),
        updated_at = now(),
        updated_by = current_user_id,
        updated_device_id = p_device_id
    WHERE client_id = p_client_id;

    INSERT INTO public.proposal_option_history (
        client_id, organization_id, revision, snapshot,
        created_at, created_by, source_device_id
    )
    VALUES (
        p_client_id, current_org_id, next_revision, p_snapshot,
        now(), current_user_id, p_device_id
    )
    ON CONFLICT (client_id, revision) DO NOTHING;

    -- Mantém a tabela antiga compatível com telas ainda não atualizadas. A
    -- configuração local impede que o gatilho legado crie outra revisão.
    PERFORM set_config('app.proposal_snapshot_rpc', '1', true);

    DELETE FROM public.proposal_options
    WHERE client_id = p_client_id;

    FOR option_value IN SELECT value FROM jsonb_array_elements(p_snapshot)
    LOOP
        INSERT INTO public.proposal_options (
            user_id,
            organization_id,
            client_id,
            name,
            measurements,
            general_discount
        )
        VALUES (
            current_user_id,
            current_org_id,
            p_client_id,
            COALESCE(option_value->>'name', 'Opcao 1'),
            COALESCE(option_value->'measurements', '[]'::jsonb),
            COALESCE(option_value->'generalDiscount', '{}'::jsonb)
        );
    END LOOP;

    UPDATE public.clients
    SET last_updated = now()
    WHERE id = p_client_id;

    RETURN jsonb_build_object(
        'status', 'saved',
        'revision', next_revision
    );
END;
$$;

REVOKE ALL ON FUNCTION public.save_proposal_options_snapshot(bigint, jsonb, bigint, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.save_proposal_options_snapshot(bigint, jsonb, bigint, text) TO authenticated;

-- Aplica somente os campos alterados pelo aparelho. O snapshot continua sendo
-- a fonte canônica, mas deixa de trafegar inteiro a cada pequena edição.
CREATE OR REPLACE FUNCTION public.apply_proposal_operations(
    p_snapshot jsonb,
    p_operations jsonb
)
RETURNS jsonb
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    result_snapshot jsonb := COALESCE(p_snapshot, '[]'::jsonb);
    operation_value jsonb;
    operation_type text;
    option_id text;
    measurement_id text;
    option_value jsonb;
    option_payload jsonb;
    measurement_payload jsonb;
    updated_option jsonb;
    updated_measurements jsonb;
BEGIN
    IF jsonb_typeof(result_snapshot) <> 'array' THEN
        RAISE EXCEPTION 'Snapshot de medidas deve ser um array';
    END IF;

    IF jsonb_typeof(p_operations) <> 'array' THEN
        RAISE EXCEPTION 'Operacoes de medidas devem ser um array';
    END IF;

    FOR operation_value IN SELECT value FROM jsonb_array_elements(p_operations)
    LOOP
        operation_type := operation_value->>'type';
        option_id := operation_value->>'optionId';

        CASE operation_type
            WHEN 'upsert_option' THEN
                option_payload := operation_value->'option';
                IF jsonb_typeof(option_payload) <> 'object' OR option_id IS NULL THEN
                    RAISE EXCEPTION 'Operacao upsert_option invalida';
                END IF;

                option_value := NULL;
                SELECT item.value INTO option_value
                FROM jsonb_array_elements(result_snapshot) item
                WHERE item.value->>'id' = option_id
                LIMIT 1;

                IF option_value IS NULL THEN
                    updated_option := option_payload
                        || jsonb_build_object('id', operation_value->'optionId')
                        || jsonb_build_object('measurements', '[]'::jsonb);
                    result_snapshot := result_snapshot || jsonb_build_array(updated_option);
                ELSE
                    updated_option := option_value
                        || option_payload
                        || jsonb_build_object('id', option_value->'id')
                        || jsonb_build_object(
                            'measurements',
                            COALESCE(option_value->'measurements', '[]'::jsonb)
                        );

                    SELECT COALESCE(
                        jsonb_agg(
                            CASE
                                WHEN item.value->>'id' = option_id THEN updated_option
                                ELSE item.value
                            END
                            ORDER BY item.ordinality
                        ),
                        '[]'::jsonb
                    )
                    INTO result_snapshot
                    FROM jsonb_array_elements(result_snapshot) WITH ORDINALITY item(value, ordinality);
                END IF;

            WHEN 'delete_option' THEN
                IF option_id IS NULL THEN
                    RAISE EXCEPTION 'Operacao delete_option invalida';
                END IF;

                SELECT COALESCE(jsonb_agg(item.value ORDER BY item.ordinality), '[]'::jsonb)
                INTO result_snapshot
                FROM jsonb_array_elements(result_snapshot) WITH ORDINALITY item(value, ordinality)
                WHERE item.value->>'id' <> option_id;

            WHEN 'upsert_measurement' THEN
                measurement_payload := operation_value->'measurement';
                measurement_id := measurement_payload->>'id';
                IF option_id IS NULL
                   OR jsonb_typeof(measurement_payload) <> 'object'
                   OR measurement_id IS NULL THEN
                    RAISE EXCEPTION 'Operacao upsert_measurement invalida';
                END IF;

                option_value := NULL;
                SELECT item.value INTO option_value
                FROM jsonb_array_elements(result_snapshot) item
                WHERE item.value->>'id' = option_id
                LIMIT 1;

                IF option_value IS NULL THEN
                    RAISE EXCEPTION 'Opcao % nao existe para receber a medida', option_id;
                END IF;

                IF EXISTS (
                    SELECT 1
                    FROM jsonb_array_elements(COALESCE(option_value->'measurements', '[]'::jsonb)) measurement
                    WHERE measurement.value->>'id' = measurement_id
                ) THEN
                    SELECT COALESCE(
                        jsonb_agg(
                            CASE
                                WHEN measurement.value->>'id' = measurement_id THEN measurement_payload
                                ELSE measurement.value
                            END
                            ORDER BY measurement.ordinality
                        ),
                        '[]'::jsonb
                    )
                    INTO updated_measurements
                    FROM jsonb_array_elements(COALESCE(option_value->'measurements', '[]'::jsonb))
                        WITH ORDINALITY measurement(value, ordinality);
                ELSE
                    updated_measurements := COALESCE(option_value->'measurements', '[]'::jsonb)
                        || jsonb_build_array(measurement_payload);
                END IF;

                updated_option := jsonb_set(option_value, '{measurements}', updated_measurements, true);
                SELECT COALESCE(
                    jsonb_agg(
                        CASE
                            WHEN item.value->>'id' = option_id THEN updated_option
                            ELSE item.value
                        END
                        ORDER BY item.ordinality
                    ),
                    '[]'::jsonb
                )
                INTO result_snapshot
                FROM jsonb_array_elements(result_snapshot) WITH ORDINALITY item(value, ordinality);

            WHEN 'delete_measurement' THEN
                measurement_id := operation_value->>'measurementId';
                IF option_id IS NULL OR measurement_id IS NULL THEN
                    RAISE EXCEPTION 'Operacao delete_measurement invalida';
                END IF;

                option_value := NULL;
                SELECT item.value INTO option_value
                FROM jsonb_array_elements(result_snapshot) item
                WHERE item.value->>'id' = option_id
                LIMIT 1;

                IF option_value IS NOT NULL THEN
                    SELECT COALESCE(
                        jsonb_agg(measurement.value ORDER BY measurement.ordinality),
                        '[]'::jsonb
                    )
                    INTO updated_measurements
                    FROM jsonb_array_elements(COALESCE(option_value->'measurements', '[]'::jsonb))
                        WITH ORDINALITY measurement(value, ordinality)
                    WHERE measurement.value->>'id' <> measurement_id;

                    updated_option := jsonb_set(option_value, '{measurements}', updated_measurements, true);
                    SELECT COALESCE(
                        jsonb_agg(
                            CASE
                                WHEN item.value->>'id' = option_id THEN updated_option
                                ELSE item.value
                            END
                            ORDER BY item.ordinality
                        ),
                        '[]'::jsonb
                    )
                    INTO result_snapshot
                    FROM jsonb_array_elements(result_snapshot) WITH ORDINALITY item(value, ordinality);
                END IF;

            WHEN 'set_option_order' THEN
                IF jsonb_typeof(operation_value->'optionIds') <> 'array' THEN
                    RAISE EXCEPTION 'Operacao set_option_order invalida';
                END IF;

                SELECT COALESCE(
                    jsonb_agg(ordered.value ORDER BY ordered.requested_position, ordered.original_position),
                    '[]'::jsonb
                )
                INTO result_snapshot
                FROM (
                    SELECT
                        item.value,
                        item.ordinality AS original_position,
                        COALESCE(
                            (
                                SELECT requested.ordinality
                                FROM jsonb_array_elements(operation_value->'optionIds')
                                    WITH ORDINALITY requested(value, ordinality)
                                WHERE requested.value::text = item.value->>'id'
                                LIMIT 1
                            ),
                            1000000000 + item.ordinality
                        ) AS requested_position
                    FROM jsonb_array_elements(result_snapshot)
                        WITH ORDINALITY item(value, ordinality)
                ) ordered;

            WHEN 'set_measurement_order' THEN
                IF option_id IS NULL
                   OR jsonb_typeof(operation_value->'measurementIds') <> 'array' THEN
                    RAISE EXCEPTION 'Operacao set_measurement_order invalida';
                END IF;

                option_value := NULL;
                SELECT item.value INTO option_value
                FROM jsonb_array_elements(result_snapshot) item
                WHERE item.value->>'id' = option_id
                LIMIT 1;

                IF option_value IS NOT NULL THEN
                    SELECT COALESCE(
                        jsonb_agg(ordered.value ORDER BY ordered.requested_position, ordered.original_position),
                        '[]'::jsonb
                    )
                    INTO updated_measurements
                    FROM (
                        SELECT
                            measurement.value,
                            measurement.ordinality AS original_position,
                            COALESCE(
                                (
                                    SELECT requested.ordinality
                                    FROM jsonb_array_elements(operation_value->'measurementIds')
                                        WITH ORDINALITY requested(value, ordinality)
                                    WHERE requested.value::text = measurement.value->>'id'
                                    LIMIT 1
                                ),
                                1000000000 + measurement.ordinality
                            ) AS requested_position
                        FROM jsonb_array_elements(COALESCE(option_value->'measurements', '[]'::jsonb))
                            WITH ORDINALITY measurement(value, ordinality)
                    ) ordered;

                    updated_option := jsonb_set(option_value, '{measurements}', updated_measurements, true);
                    SELECT COALESCE(
                        jsonb_agg(
                            CASE
                                WHEN item.value->>'id' = option_id THEN updated_option
                                ELSE item.value
                            END
                            ORDER BY item.ordinality
                        ),
                        '[]'::jsonb
                    )
                    INTO result_snapshot
                    FROM jsonb_array_elements(result_snapshot) WITH ORDINALITY item(value, ordinality);
                END IF;

            ELSE
                RAISE EXCEPTION 'Tipo de operacao de medidas desconhecido: %', operation_type;
        END CASE;
    END LOOP;

    RETURN result_snapshot;
END;
$$;

